void main(List<String> argv) {
  final StringBuffer out = StringBuffer();
  out.writeln('// Generated by tool/kernel_check.dart — do not edit.');
  out.writeln('var __agora_results = [];');
  int n = 0;

  for (final Map<String, Object?> c in _cases) {
    final String op = '${c['op']}';
    final Map<String, dynamic> args = (c['args'] as Map)
        .cast<String, dynamic>();
    final String js = PageScript.call(op, args);

    // Sanity: the wrapper must actually embed our op name and argument blob.
    if (!js.contains('agoraKernel')) {
      stderr.writeln('FAIL: $op produced no kernel reference');
      exit(2);
    }
    if (!js.startsWith('(function(){try{return (')) {
      stderr.writeln('FAIL: $op missing try/catch wrapper');
      exit(2);
    }
    out.writeln('// ---- $op ----');
    out.writeln('__agora_results.push($js);');
    n++;
  }

  // Also assert the wrapper's own error path is syntactically sound.
  out.writeln('// ---- negative: unknown op must return, not throw ----');
  out.writeln('__agora_results.push(${PageScript.call('__no_such_op__')});');
  n++;

  stdout.write(out.toString());
  stderr.writeln('generated $n expressions');
  if (argv.contains('--quiet')) exit(0);
}
