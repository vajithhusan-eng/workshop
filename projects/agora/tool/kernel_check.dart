// Validates that every PageScript op produces syntactically valid JavaScript.
//
// Dart's analyzer cannot parse JS, and a single typo in the page kernel would
// otherwise only surface as a mysterious "nothing happens" bug when Agora
// talks to a real AI site. This harness renders each op through the real
// code path and hands the result to `node --check`.
//
// Usage:
//   dart run tool/kernel_check.dart          # writes JS to stdout
//   dart run tool/kernel_check.dart --run    # also executes against a stub DOM
import 'dart:io';

import 'package:agora/core/adapters/page_script.dart';

/// Each op together with representative arguments.
const List<Map<String, Object?>> _cases = <Map<String, Object?>>[
  <String, Object?>{'op': 'ping', 'args': <String, Object?>{}},
  <String, Object?>{
    'op': 'find',
    'args': <String, Object?>{
      'spec': <String, Object?>{
        'css': <String>['#composer', 'div[contenteditable=true]'],
        'text': <String>['send a message'],
      },
    },
  },
  <String, Object?>{
    'op': 'exists',
    'args': <String, Object?>{
      'spec': <String, Object?>{
        'css': <String>['.x'],
      },
    },
  },
  <String, Object?>{
    'op': 'count',
    'args': <String, Object?>{
      'spec': <String, Object?>{
        'css': <String>['.x'],
      },
    },
  },
  <String, Object?>{
    'op': 'write',
    'args': <String, Object?>{
      'spec': <String, Object?>{
        'css': <String>['textarea'],
      },
      'text': 'he said "hi"\\ and \nnewline\ttab — em-dash ünïcode  </script>',
    },
  },
  <String, Object?>{
    'op': 'readComposer',
    'args': <String, Object?>{
      'spec': <String, Object?>{
        'css': <String>['textarea'],
      },
    },
  },
  <String, Object?>{
    'op': 'pressEnter',
    'args': <String, Object?>{
      'spec': <String, Object?>{
